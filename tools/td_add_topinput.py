#!/usr/bin/env python
"""TOP Input: hand the sidecar an image instead of opening a camera.

    RUN IT
        run("<repo>/tools/td_add_topinput.py")

    or through the chain: tools/td_rebuild.py, layer "topinput".

WHAT IT ADDS
    in_frames      an In TOP - the COMP's image input
    frames_write   a Script TOP that copies it into the shared buffer
    frames_pull    an Execute DAT that cooks the writer every frame while capturing
    Inputmode      Camera | TOP Input, on General above `Camera`
    Framesbuffer   where the buffer lives, on Advanced beside the other two

WHY A PULLER. TouchDesigner cooks an operator when something DOWNSTREAM asks for it;
the writer's `Tick` expression only marks it dirty. Nothing downstream reads
`frames_write` - `video_source` takes `in_frames` directly and a DAT consumer pulls no
TOP - so with the network editor closed it cooked once and the sidecar waited forever
for a frame. MEASURED: 4 cooks in 3,700 frames. `frames_pull` asks for it each frame,
only while `Active` is on in TOP Input mode, so a project in Camera mode pays nothing.

WHY A BUFFER AND NOT A PIPE. It is the transport this project already has: the mask
and the depth map arrive the same way, `appletd/maskbuf.py` is a seqlock rather than a
lock so neither side can block the other, and the reader gets a whole frame or the
previous one - never half of each.

WHAT IT COSTS, MEASURED (docs/BENCHMARKS.md): the readback is 0.26 ms at 720p and
0.57 at 1080p; the copy into the buffer about 0.5 at 1080p. `numpyArray(delayed=True)`
is what keeps the readback there - `delayed=False` forces a GPU sync and spikes to
3.3 ms at 720p. The cost of `delayed` is one frame of latency on a path that is already
a frame behind.

THE PIXELS ARE NOT TOUCHED. `numpyArray` returns float32 RGBA with the bottom row first,
whatever the TOP's format, and that is what goes into the buffer - 33 MB a frame at
1080p, copied once. The five-pass conversion to BGRA bytes that used to run here cost
14 ms a frame at 1080p on TouchDesigner's main thread; Vision reads the float buffer as
it is, and the sidecar tells it the rows are upside down (appletd/frames.py).

NO CAMERA PERMISSION IS NEEDED in this mode, because no capture device is opened. That
is the second reason to want it, after "my image is not a camera".

Ref: appletd/frames.py, docs/BUILD_PLAN.md step 28.
"""

import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MASTER_PATH = "/project1/appletd"

IN_TOP = "in_frames"
WRITER = "frames_write"
CALLBACKS = "frames_callbacks"
PULL = "frames_pull"
DEFAULT_FRAMES_PATH = "/tmp/appletd_frames.buf"

# The puller. `cook()` without `force`: the writer is dirty every frame through its
# `Tick` expression, so this is one cook per frame and never two.
PULL_SOURCE = '''# Generated by tools/td_add_topinput.py
#
# A Script TOP cooks only when something downstream asks. In TOP Input mode nothing
# does - the video path reads `in_frames`, a DAT reads no TOP - so this asks, once a
# frame, while there is a sidecar to feed.

# The camera path delivers 30 frames a second and every request is measured
# against that; TouchDesigner runs at 60. Cooking the writer every frame would hand
# the sidecar twice the frames Vision can use, at twice the readback cost.
TARGET_FPS = 30


def onFrameStart(frame):
    comp = op(%(comp)r)
    if comp is None:
        return
    if str(comp.par.Inputmode.eval()) != "top" or not bool(comp.par.Active.eval()):
        return
    every = max(1, int(round(project.cookRate / TARGET_FPS)))
    if frame %% every:
        return
    writer = comp.op(%(writer)r)
    if writer is not None:
        writer.cook()
'''

# The Script TOP's cook. Writes whatever the In TOP holds into the shared buffer.
WRITER_SOURCE = '''# Generated by tools/td_add_topinput.py
#
# One direction only: TouchDesigner -> sidecar. Every other image operator in this
# component runs the other way.
import os
import sys

%(resolver)s
_ROOT = _find_package_root(op(%(comp)r))
if _ROOT and _ROOT not in sys.path:
    sys.path.append(_ROOT)              # append, never insert

import numpy

from appletd.maskbuf import DTYPE_F32, MaskWriter

# One writer for the life of the operator, reopened when the geometry changes. Opening
# per cook would mmap and unmap 33 MB every frame.
_WRITER = None
_SHAPE = None
# What the operator shows: a 2x2 heartbeat that flips each cook, so a writer that is
# running can be told from one that is not without uploading the frame back to the
# GPU - which cost as much as the readback it followed.
_BEAT = [numpy.full((2, 2, 4), 255, dtype=numpy.uint8),
         numpy.zeros((2, 2, 4), dtype=numpy.uint8)]
_COOKS = 0


def _writer(path, width, height):
    global _WRITER, _SHAPE
    if _WRITER is not None and _SHAPE == (path, width, height):
        return _WRITER
    if _WRITER is not None:
        _WRITER.close()
    _WRITER = MaskWriter(path, width, height, components=4, dtype=DTYPE_F32)
    _SHAPE = (path, width, height)
    print("[appletd] TOP Input writing %%dx%%d float32 to %%s" %% (width, height, path))
    return _WRITER


def onCook(scriptOp):
    comp = op(%(comp)r)
    if comp is None:
        return
    # Checked HERE and not with allowCooking, which raises on a bare operator - the
    # same arrangement seg_mask uses. The `Tick` expression already stops the cook
    # when the mode is Camera; this is the second line of defence.
    if str(comp.par.Inputmode.eval()) != "top":
        return
    source = scriptOp.inputs[0] if scriptOp.inputs else None
    if source is None:
        return
    width, height = int(source.width), int(source.height)
    if width <= 0 or height <= 0:
        return
    # `delayed=True` returns the PREVIOUS frame and does not stall the GPU.
    # MEASURED: delayed=False costs 3.3 ms at 720p in the worst case against 0.26
    # median, and the frame it buys is one this path is already behind by.
    pixels = source.numpyArray(delayed=True)
    if pixels is None:
        return
    # RGBA, FLOAT32, bottom row first - whatever the TOP's own format is - and it goes
    # into the buffer EXACTLY SO. No flip, no swizzle, no clip, no cast: Vision reads a
    # float RGBA buffer as it is, and the sidecar tells it the rows are upside down.
    # Every one of those passes was a walk over 33 MB on this thread at 1080p.
    #
    # A memoryview rather than `.tobytes()`, which would be a second copy of the same
    # 33 MB (MEASURED: 0.48 ms against 1.01 for the copy into the buffer).
    if pixels.dtype != numpy.float32 or not pixels.flags["C_CONTIGUOUS"]:
        pixels = numpy.ascontiguousarray(pixels, dtype=numpy.float32)
    _writer(str(comp.par.Framesbuffer.eval()), width, height).write(
        memoryview(pixels).cast("B"))
    global _COOKS
    _COOKS += 1
    scriptOp.copyNumpyArray(_BEAT[_COOKS & 1])
'''


def main():
    import td

    if REPO_ROOT not in sys.path:
        sys.path.append(REPO_ROOT)
    for stale in [n for n in list(sys.modules)
                  if n == "appletd" or n.startswith("appletd.")]:
        del sys.modules[stale]
    from appletd.td_layout import (
        PACKAGE_ROOT_SOURCE,
        ensure,
        keep_layout,
        master_xy,
    )

    comp = op(MASTER_PATH)
    if comp is None:
        print("no COMP at %s - run tools/td_build_vision.py first" % MASTER_PATH)
        return

    # ONE call, so `Keeplayout` reaches every operator this builder places.
    # Twenty-odd of them wrote nodeX/nodeY straight from the table, so
    # tidying the master network and switching the parameter on lasted
    # exactly until the next rebuild.
    keep = keep_layout(comp)

    print("=" * 70)
    print("topinput: an image input on %s" % comp.path)
    print("=" * 70)

    general = advanced = None
    for page in comp.customPages:
        if page.name == "General":
            general = page
        elif page.name == "Advanced":
            advanced = page
    if general is None or advanced is None:
        print("FAIL no General/Advanced page - run tools/td_build_vision.py first")
        return

    existing = {par.name for par in comp.customPars}
    if "Inputmode" not in existing:
        # A MENU and not a toggle: "Camera or not" is two states today and the third
        # - a file, a stream - would have nowhere to go on a toggle.
        mode = general.appendMenu("Inputmode", label="Input Mode")[0]
        mode.menuNames = ["camera", "top"]
        mode.menuLabels = ["Camera", "TOP Input"]
        mode.default = "camera"
    if "Framesbuffer" not in existing:
        # Beside `Maskbuffer` and `Depthbuffer` on Advanced: a path that has to match
        # on both sides is not something a consumer of this COMP chooses.
        path = advanced.appendStr("Framesbuffer", label="Frames Buffer")[0]
        path.default = DEFAULT_FRAMES_PATH
        path.val = DEFAULT_FRAMES_PATH

    # -- the input, and the writer ----------------------------------------
    in_top = ensure(comp, td.inTOP, IN_TOP, master_xy(IN_TOP), keep)
    # PRESERVED, never recreated - an In TOP IS the COMP's input connector, and
    # destroying it disconnects whatever the project had wired to it.

    # The code goes in a DAT, not on the operator: a Script TOP has no `.text` - its
    # cook lives in whatever its `callbacks` parameter points at.
    callbacks = ensure(comp, td.textDAT, CALLBACKS, master_xy(CALLBACKS), keep)
    callbacks.text = WRITER_SOURCE % {"comp": comp.path,
                                      "resolver": PACKAGE_ROOT_SOURCE}

    existed = comp.op(WRITER) is not None
    writer = ensure(comp, td.scriptTOP, WRITER, master_xy(WRITER), keep)
    if not existed:
        # Creating a Script TOP auto-docks a callbacks DAT of its own. Destroyed, or
        # two of them sit there and only one is the one being edited - the same
        # cleanup td_add_segmentation.py does for `seg_mask`.
        for child in list(comp.children):
            if child.name.startswith(WRITER + "_callbacks") and child.valid:
                child.destroy()
    writer.par.callbacks = callbacks.path
    writer.inputConnectors[0].connect(in_top)
    writer.color = (0.35, 0.45, 0.5)

    tick_page = None
    for page in writer.customPages:
        if page.name == "Tick":
            tick_page = page
            break
    if tick_page is None:
        tick_page = writer.appendCustomPage("Tick")
    if not hasattr(writer.par, "Tick"):
        tick_page.appendInt("Tick", label="Tick (drives the cook - do not set)")
    # An input-less Script TOP is never dirtied on its own, and this one has an input
    # that only changes when the project changes it. The expression goes CONSTANT when
    # the mode is Camera, which is what stops the cook (DESIGN.md 2.21).
    writer.par.Tick.expr = (
        "absTime.frame if op.Appletd.par.Inputmode == 'top' else 0")
    writer.par.Tick.readOnly = True

    pull = ensure(comp, td.executeDAT, PULL, master_xy(PULL), keep)
    pull.text = PULL_SOURCE % {"comp": comp.path, "writer": WRITER}
    pull.par.active = True
    pull.par.framestart = True

    print("   %-14s <- the COMP's image input" % IN_TOP)
    print("   %-14s -> %s" % (WRITER, comp.par.Framesbuffer.eval()))
    print("   Input Mode  = %s" % comp.par.Inputmode.eval())
    print()
    print("   verified. In TOP Input mode no camera is opened at all, so no camera")
    print("   permission is needed. The frame goes into the buffer as float32,")
    print("   untouched; MEASURED at 1080p: readback 0.57 ms + copy 0.48 ms.")


main()
