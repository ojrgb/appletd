# find and destroy them. Renaming them to `appletd*` would leave it hunting for
# names that never existed, and the old operators would survive for ever.
SUPERSEDED = ("visionhands", "visionpose", "visionface",
              "visionhands_osc", "visionpose_osc", "visionface_osc")


def main():
    import td

    print("=" * 70)
    print("vision: building the master COMP and its three streams")
    print("=" * 70)

    import sys
    if REPO_ROOT not in sys.path:
        sys.path.append(REPO_ROOT)
    # TouchDesigner caches our modules for the life of the process (DESIGN.md 2.11).
    for stale in [n for n in list(sys.modules)
                  if n == "appletd" or n.startswith("appletd.")]:
        del sys.modules[stale]
    # `td_layout` is every coordinate a MASTER-level operator gets. One table,
    # because seven builders place operators in here and two of them once chose the
    # same spot with nothing able to notice.
    from appletd.install import PYTHON_URL
    from appletd.sidecar import DEFAULT_DEPTH_PATH, DEFAULT_MASK_PATH
    from appletd.streams import (
        DEFAULT_SEGMENT_QUALITY,
        SEGMENT_QUALITIES,
        STATUS_PREFIX,
        port_for,
    )
    from appletd.td_layout import (
        COL_W,
        MAX_PINS,
        OUTPUT_ORDER,
        PACKAGE_ROOT_SOURCE,
        keep_layout,
        master_xy,
        rewire_master_chain,
        stream_row,
    )

    parent = op(PARENT_PATH)
    if parent is None:
        print("FAIL no operator at %s" % PARENT_PATH)
        return

    comp = parent.op(COMP_NAME)
    existed = comp is not None
    previous = {}
    if existed:
        # Remember what the user tuned, so a rebuild restores it rather than
        # resetting it. Every custom parameter, not a hand-maintained list: the
        # pages are built by six different scripts now and a list here would go
        # stale silently.
        previous = {par.name: par.eval() for par in comp.customPars}
    else:
        # First run: inherit whatever the COMP this supersedes was tuned to, so the
        # restructure does not quietly reset somebody's Ortho Width.
        old = parent.op("appletd")
        if old is not None:
            previous = {par.name: par.eval() for par in old.customPars}
            print("0. inheriting %d tuned parameters from %s"
                  % (len(previous), old.path))
        comp = parent.create(td.baseCOMP, COMP_NAME)
    comp.nodeX, comp.nodeY = 250, 0
    comp.color = (0.25, 0.35, 0.45)
    # Everything inside is rebuilt by this script and the six that follow it, so
    # clearing is what keeps them all idempotent. Two kinds of child are spared.
    #
    # The STREAM CHILDREN, because destroying those would throw away the networks
    # the other builders own, and they clear their own contents when they run
    # (DESIGN.md 2.11 - destroying a group orphans its consumers).
    #
    # The OSC IN CHOPS, because an OSC In CHOP only holds the channels that have
    # ARRIVED: a fresh one starts empty and regains only what is being sent right now.
    # With no sidecar running that silently drops the `sc_*` status channels, leaving
    # a plausible channel count that nothing complains about.
    #
    # And THE OUT CHOPS. An Out CHOP IS the COMP's output connector, so destroying it
    # disconnects whatever the PROJECT had wired to that output and recreating it does
    # not bring the wire back. The symptom is not an error: the orphaned consumers
    # stop pulling, so the stream stops cooking while operators on their own clocks
    # keep going and the COMP still looks busy (DESIGN.md 2.11).
    # `out1` only: `out2` and `out3` are retired below, and the merge and the delete
    # in front of out1 are cheap to rebuild because out1 itself is what external
    # wires attach to.
    kept = (set(STREAM_NAMES) | {name + "_osc" for name in STREAM_NAMES}
            | {"out1", "merge_streams", "trim_empty",
               "housekeeping_sel", "housekeeping"}
            # `out2` and `out3` are RETIRED, not kept - but they are retired further
            # down, where their consumers can be read off them first and repointed at
            # out1. Destroyed by this loop instead they would be gone before anything
            # had looked, and an orphaned input cannot be told from an empty one.
            | {"out2", "out3"}
            # AND every master-level operator another builder owns. This script used
            # to destroy them, which meant a change to the master shell dragged four
            # more builders along behind it just to put back callback DATs it had no
            # business removing - and made "rebuild the master" a five-script job.
            # Each builder owns its own operators; this one owns the shell.
            | OTHER_BUILDERS_OWN.keys()
            # The two Parameter Execute DATs that watch the render and the camera.
            # Built below; named here because this loop destroys anything it does
            # not recognise, and these were hand-built first and would have been
            # deleted by the next chain run.
            | {"renderchange", "camchange"})
    # WHERE THINGS WERE, taken BEFORE the destroy loop. This builder recreates its
    # own operators - `sidecar_control`, `sidecar_callbacks`, `status` and the rest -
    # rather than reusing them, so by the time each is placed there is nothing left
    # to ask where it used to be, and `Keeplayout` could not hold them however it was
    # written. Somebody who tidied the master network watched it un-tidy itself on
    # every rebuild, which is precisely what that parameter promises not to do.
    #
    # Restored after creation, and only for a name that WAS here: a genuinely new
    # operator is placed from the table, because "leave it alone" for something that
    # has never existed means piling it wherever TouchDesigner dropped it.
    was_at = {child.name: (child.nodeX, child.nodeY) for child in comp.children}
    for child in list(comp.children):
        if child.name not in kept:
            child.destroy()
    print("1. %s %s" % ("reusing" if existed else "created", comp.path))

    # The Global OP Shortcut, and it is load-bearing rather than convenience: every
    # expression in every nested group reads `op.Appletd.par.X`. Set BEFORE anything
    # that writes such an expression, or the first cook reports a name error.
    comp.par.opshortcut = OP_SHORTCUT

    # -- retire what the page reorganisation replaces ----------------------
    # BEFORE anything is appended, because four of these names are being re-created
    # on a different page and TouchDesigner will not hold the same custom parameter
    # name twice. `previous` was captured above, so a tuned value survives the move.
    #
    # WHY the Sidecar page is gone: it named an implementation detail. What was on it
    # is operational - which camera, which streams, is it running - so it belongs on
    # General; the two genuinely diagnostic parameters belong on Advanced.
    # SNAPSHOT EVERY CUSTOM VALUE ACROSS THE DESTROY-AND-RE-APPEND PASS.
    #
    # Destroying and re-appending parameters on one page has been observed to move
    # values on OTHER pages - toggles this script does not touch, does not name and has
    # no opinion about. The mechanism is not established and nothing here claims one.
    #
    # What matters is that the damage is SILENT: a wrong toggle is indistinguishable
    # from a deliberate setting. So read everything before, write back anything that
    # changed after, and PRINT what moved.
    #
    # `previous` already captures the MOVED_PARS values for their own round trip;
    # this is the wider net, for parameters nothing here was supposed to touch.
    was = {par.name: par.eval() for par in comp.customPars}
    retired_pars = _retire(comp, RETIRED_PARS + MOVED_PARS, RETIRED_PAGES)

    # -- the shared parameters --------------------------------------------
    page = _page(comp, "General")

    # Is the capture process running. ONE toggle, replacing a Start pulse and a Stop
    # pulse, because a pulse pair cannot show state and this is state.
    #
    # THE HONEST CAVEAT, and it is on the label: a toggle implies the truth and this
    # one is only a COMMAND. The process can die on its own - a camera unplugged, a
    # crash, someone killing it from a terminal - and the toggle would still read on.
    # `sc_uptime_s` on the status channels is the truth, because it comes FROM the
    # process; `Capturepid` on Advanced is what we last started.
    par_active = page.appendToggle("Active", label="Active")[0]
    par_active.default = False

    # Which camera, as a SUBSTRING of the device name - which is what the sidecar's
    # `--camera` has always taken, so this parameter and the flag cannot disagree.
    #
    # A string and not a MENU, deliberately. A menu would have to be populated at
    # build time, and this machine has an OBS virtual camera, a Camo camera and an
    # iPhone alongside the built-in one: a baked list goes wrong the moment a device
    # is unplugged, and a menu whose entries no longer exist is worse than a field
    # that simply does not match. `Listcameras` prints what is actually there.
    # RESTART, beside Active. Pressing Active twice does the same thing - `start()`
    # stops first - but nobody knows that from looking at a toggle, and "restart to
    # apply" appears on nine labels on this page.
    # Under `Active`, because it changes what `Active` does: with it on, a launch flag
    # applies itself three seconds later instead of waiting for somebody to notice the
    # status light. Appended like every other parameter on this page - `_retire` has
    # already run, so this function owns the page and appends unconditionally.
    par_autorefresh = page.appendToggle("Autorefresh", label="Auto Refresh")[0]
    par_autorefresh.default = False

    # Outputs nothing is feeding, taken off the COMP. See `apply_output_visibility`
    # for why they only come off the END.
    par_hide = page.appendToggle("Hideunused", label="Hide Unused Outputs")[0]
    par_hide.default = False

    # How long `Freeze` waits. 0 is immediate, which is the default and what the
    # pulse meant before this existed.
    par_freezetimer = page.appendInt("Freezetimer", label="Freeze Timer Seconds")[0]
    par_freezetimer.default = 0
    par_freezetimer.normMin, par_freezetimer.normMax = 0, 30

    # The camera image itself, as a TOP. Under `Auto Refresh` because it belongs to
    # the capture block rather than to any one stream, and it is what the overlays
    # composite onto.
    par_video = page.appendToggle("Outputvideo", label="Output Video")[0]
    par_video.default = False

    page.appendPulse("Restartcapture", label="Restart")

    # Hold what is on the outputs and stop capturing, so an effect can be built
    # against a still frame without the camera and the model running behind it.
    # Released by turning `Active` back on.
    page.appendPulse("Freeze", label="Freeze  (hold outputs, stop capture)")

    # THE STATUS. One read-only string, and no colour swatch: TouchDesigner renders a
    # read-only value in its own colour anyway, and an RGB parameter costs three
    # visible float fields to say what the word already says.
    #
    # Three states, and the middle one is why this exists: `Requires Restart` means a
    # process IS running but a launch flag has changed since it started, so the panel
    # and the process disagree. Without it that state is invisible.
    par_state = page.appendStr("Capturestate", label="Status")[0]
    par_state.readOnly = True

    # A MENU rather than a text field. A baked list goes wrong the moment a device is
    # unplugged, so the list REFRESHES: `Refresh Camera List` re-enumerates, and a
    # device that has gone is KEPT as an entry rather than silently swapped for
    # whatever is first.
    #
    # The blank entry is "(default)" - whatever `engine.py` picks on its own.
    #
    # Exact names, not substrings. `--camera` still matches on a substring, so driving
    # the sidecar by hand is unaffected.
    # `CAMERA_DEFAULT` and not an empty string: TouchDesigner rejects "" as a menu
    # NAME at the C level - `SystemError: error return without exception set`, with no
    # Python exception to catch. So the "use the engine's own default" entry needs a
    # real token, and `start()` maps it back to blank.
    par_camera = page.appendMenu("Camera", label="Camera")[0]
    # Seeded with ONLY the default entry, and defaulting to it. `DEFAULT_CAMERA` is
    # "MacBook" - a SUBSTRING, which was right for a text field matched with `in` and
    # is wrong as a menu entry, because no device is called that. The real names arrive
    # from `refresh_cameras` at the end of the build; until then "(default)" is the
    # honest option, and it behaves exactly as the old blank field did: no `--camera`
    # is passed and engine.py's own default decides.
    par_camera.menuNames = [CAMERA_DEFAULT]
    par_camera.menuLabels = ["(default)"]
    par_camera.default = CAMERA_DEFAULT
    page.appendPulse("Listcameras", label="Refresh Camera List")

    # Slot assignment: h0 = the right hand, h1 = the left, whichever order Vision
    # reports them in (appletd/slots.py). NOTE the consequence: with this on, a
    # single LEFT hand puts nothing in h0, so every h0_* channel reads zero.
    par_slots = page.appendToggle(
        "Slotassign", label="Assign Slots")[0]
    par_slots.default = True

    # Which Vision requests the sidecar runs. LAUNCH FLAGS, read once when the
    # process starts (DESIGN.md 6.4), which is what `Capturestate` reports. What
    # they save is INFERENCE, not channels: a disabled stream keeps every channel it
    # has, reading zero, because a channel that vanishes breaks its consumers
    # silently (DESIGN.md 6.2).
    #
    # TWO effects, and the label says so. The flag reaches the
    # sidecar only on a restart, but `tools/td_add_groups.py` also binds
    # `allowCooking` on the stream's child COMP to this toggle, and THAT takes effect
    # at once. So turning a stream off stops its network processing the zeros the
    # sidecar still sends - which is the saving - and turning one on unfreezes the
    # network immediately while the inference waits for a restart.
    stream_pars = {}
    for stream, label, default in (("hands", "Hands", True),
                                   ("pose", "Body Pose", False),
                                   ("face", "Face", False),
                                   # SEGMENT is the fourth request and the odd one
                                   # out: it has no OSC port and publishes a mask to
                                   # a shared mmap instead. Same launch-flag
                                   # mechanism, so it belongs beside its three
                                   # siblings rather than on a page of its own -
                                   # "which Vision requests am I paying for" is one
                                   # question. What it gates on the TD side is the
                                   # Script TOP that reads the buffer, not an
                                   # `allowCooking` on a stream COMP, because
                                   # `allowCooking` cannot be disabled on anything
                                   # that is not a COMP (DESIGN.md 2.20).
                                   ("segment", "Segmentation Mask", False),
                                   # DEPTH, and the label carries the cost because
                                   # this one is in a class of its own: MEASURED at
                                   # 23.00 ms a frame against hands' 3.41
                                   # (DESIGN.md 2.22), which is most of a 30 fps
                                   # frame interval on its own. It also needs a
                                   # 47 MB model that is not in this repo - see
                                   # docs/DEPTH.md and ./tools/fetch_models.sh.
                                   ("depth", "Depth Map  (23 ms/frame)", False)):
        par = stream_pars.setdefault(stream, page.appendToggle(
            "Stream" + stream,
            label=label)[0])
        par.default = default

    # The mask's quality: a LAUNCH FLAG, like the toggles above, because the request
    # is built when the sidecar starts. MEASURED per frame (DESIGN.md 2.18), and the
    # spread is why this is a control at all:
    #
    #     fast       2.21 ms   256x192     a HARD alpha - only 0 and 255
    #     balanced   8.54 ms   512x384     feathered
    #     accurate  30.73 ms  2016x1512    cannot hold 30 fps on its own
    #
    # All of it lands on the same serial queue as hands' 3.41 ms. Vision's OWN
    # default is `accurate`; ours is `fast`, and the menu comes from
    # appletd/streams.py so the sidecar's command line and this menu cannot
    # disagree about what a level is called.
    par_quality = page.appendMenu(
        "Segquality", label="Mask Quality")[0]
    par_quality.menuNames = list(SEGMENT_QUALITIES)
    par_quality.menuLabels = [
        "%s  (%s)" % (name.capitalize(), note) for name, note in zip(
            SEGMENT_QUALITIES,
            ("2.2 ms, 256x192, hard edge", "8.5 ms, 512x384, feathered",
             "31 ms, 2016x1512 - drops frames"), strict=True)]
    par_quality.default = DEFAULT_SEGMENT_QUALITY

    # People separated from EACH OTHER, not just from the background. A launch flag
    # like the quality beside it. The mask stops being 0/255 when this is on and
    # starts carrying an instance index per pixel, so the label says so.
    par_instances = page.appendToggle(
        "Multiperson", label="Multi-Person  (mask carries a person index)")[0]
    par_instances.default = False

    # MIRROR THE CAMERA, before Vision sees it. A launch flag, so it restarts.
    #
    # FREE, and worth saying because the obvious implementation is not: it is an
    # image ORIENTATION on the Vision request, so nothing flips a pixel in Python.
    # Everything Vision returns is mirrored with it - MEASURED, the
    # depth map comes back 8.2x closer to the mirror of the original than to the
    # original - so the mask, depth and flow TOPs need NOTHING downstream. Only
    # `video_in` does, because TouchDesigner opens the camera itself and that image
    # never goes near Vision.
    par_flip = page.appendToggle(
        "Cameraflip", label="Camera Flip  (mirror X before Vision)")[0]
    par_flip.default = False

    par_w = page.appendInt("Resw", label="Source Width")[0]
    par_h = page.appendInt("Resh", label="Source Height")[0]
    # `.default` always, `.val` only when the parameter is NEW. TD's append* reset
    # a parameter's attributes on rebuild, and a newly appended one reads 0 whatever
    # its default says - both measured, both in DESIGN.md 2.11. `previous` is the
    # record of what existed, so it answers the only question that matters here.
    par_w.default, par_h.default = DEFAULT_WIDTH, DEFAULT_HEIGHT
    # A FLOOR OF 1, because 0 here is catastrophic and invisible: `_px = x * Resw`,
    # so a zero takes every pixel coordinate in the component to zero with no error
    # anywhere. It is reachable - two aborted builds left both of these
    # at 0, because a newly appended parameter reads 0 whatever its default says
    # (DESIGN.md 2.11) and the restore pass never ran.
    #
    # `sc_src_w` reports 0 for "not stated" and `source_size` refuses to write it, so
    # nothing legitimate ever wants a zero here.
    par_w.clampMin = par_h.clampMin = True
    par_w.min = par_h.min = 1
    # THESE THREE DEFAULT TO AN EXPRESSION, not a number, and that is the point:
    # `_ty` is scaled by the RENDER's aspect, so a fixed number leaves the transform
    # on last build's aspect after a resize - a wrong position with nothing to see.
    # `is not None` rather than a bare `or`, because a render of width 0 is a real
    # reading and should not fall back.
    par_rw = page.appendInt("Renderw", label="Render Width")[0]
    par_rh = page.appendInt("Renderh", label="Render Height")[0]
    par_rw.default, par_rh.default = DEFAULT_WIDTH, DEFAULT_HEIGHT
    par_rw.defaultExpr = RENDER_W_EXPR
    par_rh.defaultExpr = RENDER_H_EXPR
    par_ortho = page.appendFloat("Orthowidth", label="Camera Ortho Width")[0]
    par_ortho.default = DEFAULT_ORTHO_WIDTH
    par_ortho.defaultExpr = ORTHO_EXPR

    # The output shaping: what LEAVES the COMP, as opposed to what it computes.
    par_screen = page.appendToggle(
        "Screenspaceonly", label="Screen Space Only (drop raw normalised)")[0]
        # ON, by the user. It shipped OFF because the raw normalised
    # channels are what every existing project reads and a toggle that ships ON
    # deletes them out from under one - true, and the reason it stayed off while there
    # were projects to break. The component now ships for people who have not built
    # against it yet, and for them the raw pair is duplicate volume: `_tx`/`_ty` in
    # the space they will actually use, or two of everything.
    #
    # Paired with `Coordspx` shipping OFF - see the note in td_add_groups.py GROUPS.
    # Dropping a channel fails loudly at its consumer; freezing one does not.
    par_screen.default = True

    # Drop the channels of every group that is not computing. The whole point of
    # the single output: a component handed to a beginner opens with a channel list
    # they can read, not 1,861 channels of which most are frozen at zero.
    #
    # ON by default, and that is a DELIBERATE reversal of DESIGN.md 6.2 for this one
    # operator. Everywhere else this system prefers a stale channel to a missing one,
    # because a channel that vanishes breaks its consumers with no error anywhere.
    # Here the user's call is the other way round and the reasoning is sound: the
    # audience is beginners, an understandable list matters more than a stable one,
    # and channels appearing and disappearing as toggles move is acceptable - even
    # useful, since it makes the toggles legible.
    #
    # It is the LAST operator before the output, so nothing inside the COMP reads
    # through it and no group's own verification is affected.
    par_empty = page.appendToggle(
        "Deleteempty", label="Delete Empty Channels")[0]
    par_empty.default = True

    # Two OUTPUT-ONLY toggles. `tools/td_add_groups.py` owns what they mean; this only
    # creates them, because every control on this page is created here so the page
    # order is decided in one place.
    #
    # Both ship ON: six points per hand is the shape worth shipping, and the rest is
    # one toggle away.
    par_tips = page.appendToggle(
        "Fingertipsonly", label="Finger Tips Only")[0]
    par_tips.default = True

    # Whether the builders may move nodes. `appletd.td_layout.placement` has the
    # rule and what it cannot protect - the short version is that it holds the group
    # COMPs, the stream shell and the OSC In CHOPs, and cannot hold operators INSIDE
    # a group, because those are destroyed and regenerated on every run.
    # The page reads in the order a user meets it: is it running, what is it
    # looking at, what is it computing, what geometry, what comes out. `sort` rather
    # than destroy-and-rebuild, because destroying a page destroys its parameters
    # and every tuned value with them.
    # ORDER IS NOT SET HERE. tools/td_add_pages.py owns it for every page, from
    # one table - two sorters disagreeing is a page whose shape depends on which
    # builder ran last.

    # -- Advanced: the internals, including two that moved off Sidecar ------
    # SHARED PAGE, and this is the one place in the repo where two builders write to
    # one: `tools/td_add_temporal.py` owns the debounce and velocity parameters here.
    # That is safe only because each appends its OWN names and each restores its own
    # stored values - the hazard the comment in td_add_filter.py warns about is two
    # scripts appending the SAME parameter, where whichever runs second resets it.
    advanced = _page(comp, "Advanced")

    # The OSC base port. The three streams take base + 0/1/2 (DESIGN.md 6.4), and
    # the OSC In CHOPs bind it through an EXPRESSION, so changing this rebinds them
    # at once while the sidecar keeps sending to the old one until it is restarted.
    # The visible symptom of that gap is `sc_uptime_s` freezing, which is the same
    # signal as a dead sidecar - so the label says restart.
    par_port = advanced.appendInt("Oscport", label="OSC Base Port")[0]
    par_port.default = OSC_PORT

    advanced.appendPulse("Printstatus", label="Print Status")
    par_pid = advanced.appendInt("Capturepid", label="Capture Process PID")[0]
    # WHERE the mask is published, and it has to match on both sides: the sidecar
    # writes here and the Script TOP reads here. On Advanced with the other
    # internals, because a consumer of this COMP does not choose it - the same
    # arrangement `Oscport` has. Owned HERE rather than by
    # tools/td_add_segmentation.py, because `start()` above needs it to exist before
    # anything has read a mask.
    # KEEP LAYOUT, moved here from Vision. It is a build-time
    # preference - whether the builders may move nodes - not something anybody touches
    # while the thing is running, and it was the odd one out among the operational
    # controls.
    par_keep = advanced.appendToggle(
        "Keeplayout", label="Keep Layout (builders leave existing nodes)")[0]
    par_keep.default = False

    # THE INSTALL PATHS, all three configurable and none of them magic. `appletd
    # .install` decides what they mean; these are only where somebody changes them.
    #
    # `Installroot` is Application Support rather than beside the .toe: always
    # writable, survives the project moving, and stamped with a version inside so two
    # .toe files cannot quietly fight over one install.
    #
    # `Sidecarpython` EMPTY means "work it out" - the probe in `install.py` tries the
    # install's own interpreter, then the documented venv, then what is on PATH, and
    # downloads one only if none of them can actually import pyobjc. Set it and it goes
    # first. A path and not a menu, because the answer is a path.
    #
    # BOTH DEFAULT TO BLANK, and that is what makes a shipped .tox installable
    # anywhere. A default of `os.path.expanduser(...)` is expanded on the machine that
    # RAN THE BUILDER, so the .tox carries one person's home directory and Install
    # points at a path nobody else has. Blank is resolved by
    # `comp.par.Installroot.eval() or install.DEFAULT_INSTALL_ROOT`, on the machine
    # that OPENS the file. Typing a path still overrides it.
    par_installroot = advanced.appendStr(
        "Installroot",
        label="Install Folder  (blank = Application Support)")[0]
    par_installroot.default = ""
    par_sidecarpy = advanced.appendStr(
        "Sidecarpython", label="Sidecar Python  (blank = find or install one)")[0]
    par_sidecarpy.default = ""
    par_pyurl = advanced.appendStr(
        "Pythonurl", label="Python Download  (pinned; blank = never download)")[0]
    par_pyurl.default = PYTHON_URL

    par_mask = advanced.appendStr("Maskbuffer", label="Mask Buffer Path")[0]
    par_mask.default = DEFAULT_MASK_PATH
    par_depthbuf = advanced.appendStr("Depthbuffer",
                                     label="Depth Buffer Path")[0]
    par_depthbuf.default = DEFAULT_DEPTH_PATH
    par_pid.readOnly = True

    # The smoothing controls sit with the other General-page controls: three
    # parameters never justified a page of their own (appletd/td_pages.py).
    filter_page = _page(comp, "General")
    # The filter's own parameters live here, not in a stream, because ONE filter
    # setting applies to all three - which is the whole reason this COMP exists.
    # `td_add_filter.py` builds a group per stream and every one of them reads these.
    par_smooth = filter_page.appendToggle("Smoothing", label="Smoothing")[0]
    par_smooth.default = True
    par_mincut = filter_page.appendFloat("Mincutoff", label="Min Cutoff (Hz)")[0]
    par_beta = filter_page.appendFloat("Beta", label="Beta (speed coefficient)")[0]
    # GUESSES, and labelled as such: what should set them is per-joint jitter, which
    # is unmeasured (docs/BUILD_PLAN.md). 1.5 Hz is a visible smoothing at rest and
    # 2.0 opens the cutoff enough to keep a fast gesture crisp.
    par_mincut.default, par_beta.default = 1.5, 2.0

    # One pass for every parameter this script owns: `.val` from `.default` only
    # where the parameter is NEW. A newly appended parameter reads 0 whatever its
    # default says (DESIGN.md 2.11), and `previous` is the record of what existed.
    owned = [("Active", par_active), ("Autorefresh", par_autorefresh),
             ("Hideunused", par_hide), ("Freezetimer", par_freezetimer),
             ("Outputvideo", par_video),
             ("Camera", par_camera),
             ("Slotassign", par_slots), ("Resw", par_w), ("Resh", par_h),
             ("Renderw", par_rw), ("Renderh", par_rh),
             ("Orthowidth", par_ortho), ("Screenspaceonly", par_screen),
             ("Keeplayout", par_keep), ("Deleteempty", par_empty),
             ("Fingertipsonly", par_tips),
             ("Segquality", par_quality), ("Multiperson", par_instances),
             ("Cameraflip", par_flip),
             ("Maskbuffer", par_mask),
             ("Depthbuffer", par_depthbuf),
             ("Oscport", par_port),
             ("Installroot", par_installroot), ("Sidecarpython", par_sidecarpy),
             ("Pythonurl", par_pyurl),
             ("Smoothing", par_smooth), ("Mincutoff", par_mincut),
             ("Beta", par_beta)]
    owned += [("Stream" + name, par) for name, par in stream_pars.items()]
    for name, parameter in owned:
        if name not in previous:
            parameter.val = parameter.default

    # A NEW parameter is put into EXPRESSION mode, so the render's size and the
    # camera's ortho width are read live rather than copied once at build. This
    # replaced three one-shot `.val =` reads : they were correct at the
    # moment the builder ran and silently stale the moment somebody resized the
    # render, and a wrong `_ty` looks exactly like a right one.
    #
    # UNCONDITIONALLY, not just when new, and that is not a lost value: the code
    # this replaces overwrote all three from `render1` and `cam1` on EVERY build, so
    # any constant sitting in one of them was put there by a builder and not by a
    # person. Type a number over the expression and the next rebuild takes it back -
    # exactly as it always did.
    for name, parameter, expression in (("Renderw", par_rw, RENDER_W_EXPR),
                                        ("Renderh", par_rh, RENDER_H_EXPR),
                                        ("Orthowidth", par_ortho, ORTHO_EXPR)):
        # Assigning `.expr` switches the parameter into expression mode by itself.
        # `ParMode` is deliberately not named here: it is not reachable as a bare
        # global or off `td` in every context a builder runs in, and reaching for it
        # cost two failed builds.
        parameter.expr = expression
        print("   %-11s %-56s -> %s" % (name, expression, parameter.eval()))

    # Anything the user had tuned wins - except a parameter now driven by an
    # expression, where the expression IS the better answer. That test replaced a
    # hardcoded list of three names checked against `render`/`camera` being present:
    # asking the parameter what mode it is in cannot fall out of step with the block
    # above, and a name list can. (It already did - deleting those two variables on
    # left the list referring to them, `main()` raised here, and three
    # parameters were left reading 0.)
    for name, value in previous.items():
        if not hasattr(comp.par, name):
            continue                    # a parameter a later builder owns
        parameter = getattr(comp.par, name)
        # A non-empty `.expr` IS "this parameter is driven by an expression", and it
        # needs no enum to ask.
        if parameter.expr:
            continue
        parameter.val = value

    # EVERY `Stream*` toggle must be in the launcher's table, or it is a control that
    # cannot reach the process it claims to control. A toggle can otherwise exist, be
    # on, have its own command-line arguments and its own report line, and still be
    # absent from the one loop that turns toggles into `--streams` - so the sidecar
    # launches without it while the panel says otherwise, and nothing complains.
    #
    # Checked HERE, in the builder, because this is the only place that can see both
    # the parameters and the table. It is the cheapest possible guard against adding a
    # request to two places out of three.
    launcher_toggles = {par_name for _name, par_name in REQUEST_TOGGLES}
    orphan_toggles = sorted(
        par.name for par in comp.customPars
        if par.name.startswith("Stream") and par.name not in launcher_toggles)
    if orphan_toggles:
        raise RuntimeError(
            "these Stream* toggles are not in REQUEST_TOGGLES, so pressing Active "
            "would launch the sidecar WITHOUT them while the panel says they are on: "
            "%s" % ", ".join(orphan_toggles))

    if retired_pars:
        # Reported because it is destructive and idempotent: the FIRST run after the
        # page reorganisation removes these, and every run after it finds nothing.
        print("2. retired %s" % ", ".join(retired_pars))
    # LAST, after every append and every default written above: put back anything that
    # moved and was not meant to. Only names present before are restored, so a
    # parameter created during this build keeps the default it was given.
    moved = []
    for par in comp.customPars:
        before = was.get(par.name)
        if before is not None and par.eval() != before:
            par.val = before
            moved.append("%s %r -> %r" % (par.name, before, par.eval()))
    if moved:
        print("   RESTORED %d parameter(s) this build moved without being written:"
              % len(moved))
        for line in moved:
            print("      " + line)
    print("   pages: %s" % ", ".join(p.name for p in comp.customPages))
    print("   Active=%s, Camera=%r, OSC base port %d, source %dx%d, render %dx%d, "
          "Orthowidth=%.3f, Smoothing=%s"
          % (bool(par_active.eval()), par_camera.eval(), par_port.eval(),
             par_w.eval(), par_h.eval(), par_rw.eval(), par_rh.eval(),
             par_ortho.eval(), bool(par_smooth.eval())))

    # -- the three streams -------------------------------------------------
    # Read once, and named `keep` so it does not shadow `keep_layout` - the shared
    # helper the rest of the builders use, imported above.
    #
    # It used to say "the loose DATs at the top level do not honour this, because
    # this script destroys and recreates them and there is nothing to preserve".
    # That was true and it was the bug: `was_at` at the top of this function now
    # remembers where they were BEFORE the destroy, and the restore pass at the end
    # puts them back.
    keep = bool(par_keep.eval())
    outputs = []
    for index, stream in enumerate(STREAM_NAMES):
        row = stream_row(index)
        osc = comp.op(stream + "_osc")
        osc_existed = osc is not None
        if osc is None:
            osc = comp.create(td.oscinCHOP, stream + "_osc")
        _at(osc, (-4 * COL_W, row), keep, osc_existed)
        # An EXPRESSION on `Oscport`, not a baked number: the port is a parameter
        # now, and the receiver has to follow it the moment it changes. The offset
        # comes from the package (DESIGN.md 6.4), so the receiver cannot end up
        # listening where the sender is not sending.
        osc.par.port.expr = "%s + %d" % (MASTER_PAR % "Oscport",
                                         port_for(stream, 0))
        osc.par.active = True

        child = comp.op(stream)
        child_existed = child is not None
        if child is None:
            child = comp.create(td.baseCOMP, stream)
            # Only a fresh child gets its shell BUILT here. An existing one already
            # holds the networks the other six builders own, and rebuilding its
            # insides would silently discard them.
            _shell(td, child)
        # But the shell's POSITIONS are re-applied every run, on a fresh child and
        # an existing one alike. Otherwise a layout change reaches new projects only
        # - which is how the master and the streams ended up laid out to two
        # different conventions at once.
        _place_shell(td, child, stream, keep)
        _at(child, (-2 * COL_W, row), keep, child_existed)
        child.color = (0.35, 0.45, 0.55)
        child.inputConnectors[0].connect(osc)

        outputs.append((stream, osc, child))
        print("3.%d %-5s port %d -> %s"
              % (index + 1, stream, osc.par.port.eval(), child.name))

    # -- ONE output ---------------------------------------------------------
    # Three streams -> one Merge -> a Delete -> one Out. changed from
    # three separate Out CHOPs, so that a project wires this component once and a
    # beginner meets one channel list rather than three.
    #
    # The names still say which stream they came from - `h0_`, `p0_`, `f0_`,
    # `pose_seq`, `face_seq` - so merging loses nothing. A Merge CHOP accepts the
    # same operator on any number of inputs silently and the only symptom is the
    # channel count, so the inputs are set from scratch here rather than patched.
    merge = comp.op("merge_streams")
    merge_existed = merge is not None
    if merge is None:
        merge = comp.create(td.mergeCHOP, "merge_streams")
    _at(merge, master_xy("merge_streams"), keep, merge_existed)
    for _attempt in range(16):
        if not merge.inputs:
            break
        merge.inputConnectors[0].disconnect()
    for index, (_stream, _osc, child) in enumerate(outputs):
        merge.inputConnectors[index].connect(child.outputConnectors[0])

    # The trim. Its LIST is written by tools/td_add_groups.py, which is the only
    # place that knows which groups are frozen - and it has to be rewritten whenever
    # a toggle moves, so it cannot be baked here.
    #
    # A SELECT rather than the Delete CHOP this started as. MEASURED on
    # the same 1,764-channel merge, median of 30 forced cooks, same 306 channels out:
    #
    #     Delete,  35 drop patterns          0.6697 ms
    #     Delete, 306 literal keep names     3.3618 ms
    #     Select, 306 literal keep names     0.0555 ms
    #
    # The Delete's cost grows with list length times input channels; the Select's
    # barely moves. Two consequences of the swap, both handled in td_add_groups.py:
    #
    #   * a keep list FAILS CLOSED. A channel nobody named is gone, where the Delete's
    #     drop list let an unnamed channel through. So EVERY attribute toggle has to
    #     rewrite the list, not just the ones that gate cooking - otherwise turning a
    #     group on would leave its channels invisible.
    #   * a Select emits in `channames` ORDER, so the list is generated in merge order
    #     to leave the output identical to the Delete's.
    #
    # And it is BYPASSED whenever nothing is frozen: an empty drop list was free for
    # the Delete, where a Select naming all 1,861 channels would not be.
    stale = comp.op("delete_empty")
    if stale is not None and stale.valid:
        stale.destroy()
        print("   retired delete_empty (a Select does the same trim 12x cheaper)")
    empty = comp.op("trim_empty")
    empty_existed = empty is not None
    if empty is None:
        empty = comp.create(td.selectCHOP, "trim_empty")
        # Bypassed, and naming everything, until td_add_groups.py writes the list.
        # Set on creation only, so the list it wrote survives a rebuild of the shell.
        empty.par.channames = "*"
        empty.bypass = True
    _at(empty, master_xy("trim_empty"), keep, empty_existed)
    empty.color = (0.5, 0.32, 0.32)
    # NOT wired to the merge directly any more. Four builders own a stage of the
    # master's data path, so the order lives in
    # `appletd.td_layout.MASTER_CHAIN` and every one of them asks for the whole chain
    # to be rewired after creating its own operator. Wiring a neighbour by name here
    # would be right only for the build order this script was written against.
    rewire_master_chain(comp)

    # The housekeeping, which the output deliberately does NOT carry: `sc_*`, `seq`
    # and `age_ms`. Asked for - they are diagnostics, and a beginner
    # reading the channel list should not have to step over them. They are one click
    # away rather than gone: this Select picks them off the merge and the Null beside
    # it is the thing to look at. Its LIST, like the trim's, is written by
    # tools/td_add_groups.py, which is the only place that knows what the output drops.
    house_sel = comp.op("housekeeping_sel")
    house_sel_existed = house_sel is not None
    if house_sel is None:
        house_sel = comp.create(td.selectCHOP, "housekeeping_sel")
        house_sel.par.channames = ""
    _at(house_sel, master_xy("housekeeping_sel"), keep, house_sel_existed)
    house_sel.inputConnectors[0].connect(merge)
    house = comp.op("housekeeping")
    house_existed = house is not None
    if house is None:
        house = comp.create(td.nullCHOP, "housekeeping")
    _at(house, master_xy("housekeeping"), keep, house_existed)
    house.inputConnectors[0].connect(house_sel)
    # Cook Type = Selective, the default, so it costs nothing until something looks.
    house.comment = ("the channels out1 does not carry: sc_*, seq, age_ms. "
                     "Diagnostics, kept where they can be inspected.")

    out = comp.op("out1")
    out_existed = out is not None
    if out is None:
        out = comp.create(td.outCHOP, "out1")
    _at(out, master_xy("out1"), keep, out_existed)
    # The connector number, pinned - see appletd/td_layout.py OUTPUT_ORDER.
    out.par.connectorder = OUTPUT_ORDER["out1"]
    # PRESERVED, never recreated - an Out CHOP IS the COMP's output connector, and
    # destroying it disconnects whatever the project had wired to it (DESIGN.md 2.11).
    # `rewire_master_chain` connects the whole path in MASTER_CHAIN order,
    # including this one - `out1` reads whatever the last stage turns out to be.
    rewire_master_chain(comp)

    # -- retire the two outputs this replaces ------------------------------
    # EVERY consumer on EVERY output connector is captured first and reconnected to
    # connector 0 afterwards. Not just the two being retired: which connector index
    # belongs to which Out CHOP is TouchDesigner's business, not something this
    # script should assume, and reconnecting a consumer that was already on out1 to
    # out1 costs nothing. Guessing the mapping and getting it wrong would silently
    # leave a project reading a dead wire.
    retired = [name for name in ("out2", "out3")
               if comp.op(name) is not None and comp.op(name).valid]
    # GUARDED. This block is a one-time migration from the three-output shape, and
    # running it unconditionally is harmless only while the COMP has CHOP outputs
    # alone: once it grows a TOP one, `outputConnectors[0]` is not necessarily the
    # CHOP, every TOP consumer is repointed at a CHOP output and TouchDesigner refuses.
    #
    # A migration that has already run must not keep running, and code that indexes a
    # connector list has to say WHICH FAMILY it means.
    if retired:
        moved = []
        for connector in comp.outputConnectors:
            for connection in list(connector.connections):
                moved.append((connection.owner, connection.index))
        for name in retired:
            comp.op(name).destroy()
        for owner, connector_index in moved:
            if owner.valid:
                owner.inputConnectors[connector_index].connect(
                    comp.outputConnectors[0])
        print("   retired %s; %d consumer%s now on the single CHOP output: %s"
              % (", ".join(retired), len(moved), "" if len(moved) == 1 else "s",
                 ", ".join(sorted({owner.name for owner, _i in moved})) or "none"))

    # The sidecar's own status channels, split out for the panel. They arrive on the
    # HANDS port (DESIGN.md 6.4) and are left in that stream as well - this is a
    # second READ of them, not a partition of the data path, which is the mistake
    # that once ate them silently.
    status = comp.create(td.selectCHOP, "status")
    status.nodeX, status.nodeY = master_xy("status")
    status.inputConnectors[0].connect(comp.op("hands_osc"))
    status.par.channames = STATUS_PREFIX + "*"

    # -- sidecar lifecycle -------------------------------------------------
    control = comp.create(td.textDAT, "sidecar_control")
    control.nodeX, control.nodeY = master_xy("sidecar_control")
    control.text = SIDECAR_CONTROL_SOURCE % {
        "resolver": PACKAGE_ROOT_SOURCE, "port": OSC_PORT,
        "comp": comp.path, "request_toggles": REQUEST_TOGGLES,
        "max_pins": MAX_PINS}

    callbacks = comp.create(td.parameterexecuteDAT, "sidecar_callbacks")
    callbacks.nodeX, callbacks.nodeY = master_xy("sidecar_callbacks")
    callbacks.text = SIDECAR_CALLBACK_SOURCE
    callbacks.par.op = comp.path
    # Active and the two pulses, PLUS every launch flag - because a launch flag
    # changing is exactly what "Requires Restart" reports, and a parameter this DAT is
    # not watching cannot report anything. Built from the same table the launcher uses.
    watched = ["Active", "Autorefresh", "Restartcapture", "Freeze", "Hideunused",
               "Outputvideo", "Handsoverlay", "Poseoverlay", "Faceoverlay",
               "Printstatus", "Listcameras",
               "Camera", "Cameraflip", "Inputmode", "Framesbuffer",
               "Slotassign", "Oscport", "Segquality", "Multiperson",
               "Flowaccuracy", "Flowbuffer",
               "Maskbuffer", "Depthbuffer"]
    watched += [par_name for _n, par_name in REQUEST_TOGGLES]
    # The depth pins live on a page tools/td_add_depth.py owns, so they may not exist
    # yet on a first build - listed by NAME regardless, because a Parameter Execute
    # DAT's `pars` is a pattern list and naming one that does not exist is harmless.
    watched += ["Depthpinson", "Depthpincount"]
    watched += ["Depthpin%d%s" % (index, suffix)
                for index in range(1, MAX_PINS + 1) for suffix in ("x", "y", "m")]
    callbacks.par.pars = " ".join(dict.fromkeys(watched))
    callbacks.par.active = True
    callbacks.par.onpulse = True
    callbacks.par.valuechange = True
    callbacks.par.custom = True

    on_exit = comp.create(td.executeDAT, "sidecar_exit")
    on_exit.nodeX, on_exit.nodeY = master_xy("sidecar_exit")
    on_exit.text = SIDECAR_EXIT_SOURCE
    on_exit.par.active = True
    on_exit.par.exit = True

    # The other half of that job: `sidecar_exit` stops the process when TouchDesigner
    # quits, this starts it when a project opens with `Active` already on.
    on_start = comp.op("sidecar_start") or comp.create(td.executeDAT, "sidecar_start")
    on_start.nodeX, on_start.nodeY = master_xy("sidecar_start")
    on_start.text = SIDECAR_START_SOURCE % {"comp": comp.path}
    on_start.par.active = True
    on_start.par.start = True
    on_start.par.create = True

    # A CHOP Execute DAT called `source_size` tried this and could not:
    # `onValueChange` fires when a channel CHANGES, and `sc_src_w` is 1280 from the
    # moment it appears and never moves again, so the callback never ran at all.
    # `reconcile_source_size()` in the launcher does it instead. Destroyed here rather
    # than left orphaned.
    stale_size = comp.op("source_size")
    if stale_size is not None:
        stale_size.destroy()

    # And once now, in case a sidecar is already running and the channel is there to
    # read. Cheap, and it means a rebuild does not leave a stale resolution behind.
    control = comp.op("sidecar_control")
    if control is not None and hasattr(control.module, "reconcile_source_size"):
        control.module.reconcile_source_size()

    # One Parameter Execute per watched operator. See WATCH_SOURCE for why an
    # expression alone does not propagate.
    #
    # The PATH is written even when the operator is absent, which is the case that
    # started this: a `render1` added later binds this DAT when it appears, so the
    # first change to its resolution is caught rather than needing the network
    # rebuilt. `parent` rather than a literal "/project1", so the COMP works
    # wherever it is dropped.
    for dat_name, op_name, watched in (("renderchange", "render1",
                                        "resolutionw resolutionh"),
                                       ("camchange", "cam1", "orthowidth")):
        watcher = comp.op(dat_name)
        if watcher is None:
            watcher = comp.create(td.parameterexecuteDAT, dat_name)
        watcher.nodeX, watcher.nodeY = master_xy(dat_name)
        watcher.text = WATCH_SOURCE
        watcher.par.op = "%s/%s" % (parent.path, op_name)
        watcher.par.pars = watched
        watcher.par.valuechange = True
        watcher.par.builtin = True
        watcher.par.custom = False
        watcher.par.active = True
        target = parent.op(op_name)
        print("   %-13s watches %s %s%s"
              % (dat_name, watcher.par.op.eval(), watched,
                 "" if target is not None else "   (absent - binds when created)"))

    notes = comp.create(td.textDAT, "notes")
    notes.nodeX, notes.nodeY = master_xy("notes")
    notes.text = MASTER_NOTES % {
        "ports": "\n".join(
            "  %-5s port %-6d -> %-5s -> out%d"
            % (name, port_for(name, OSC_PORT), name, index + 1)
            for index, name in enumerate(STREAM_NAMES))}

    # -- retire what this replaces ----------------------------------------
    # Last, and only now: everything above has to have worked first, or a
    # half-finished run would leave the old structure destroyed and the new one
    # incomplete. The OSC In CHOPs matter most - two of them on one port is a
    # stream arriving in a CHOP nobody is reading.
    retired, rewired = [], []
    for name in SUPERSEDED:
        old = parent.op(name)
        if old is None:
            continue
        # Anything wired to the old COMP is repointed at this one's matching
        # output, so a project does not silently lose its input.
        target = {"appletd": 0, "visionpose": 1, "visionface": 2}.get(name)
        if target is not None:
            for sibling in parent.children:
                if sibling is comp:
                    continue
                for conn in sibling.inputConnectors:
                    if any(x.owner is old for x in conn.connections):
                        conn.connect(comp.outputConnectors[target])
                        rewired.append("%s <- out%d" % (sibling.name, target + 1))
        old.destroy()
        retired.append(name)
    if retired:
        print("4. retired %s" % ", ".join(retired))
    if rewired:
        print("   rewired %s" % ", ".join(rewired))

    # -- report ------------------------------------------------------------
    # NOT force=True. MEASURED: a forced cook of this COMP asks every
    # child for fresh data, a group frozen by `allowCooking` cannot answer, and its
    # Out CHOP drops to ZERO channels - so the channels VANISH from the output
    # instead of holding their last value (DESIGN.md 6.2). `hands` went from 503
    # channels to 406 and every builder that ran afterwards reported false failures
    # against the empty groups. A plain cook is enough for a channel count.
    comp.cook()
    print()
    print("5. %d operators in %s" % (len(comp.children), comp.path))
    for stream, osc, child in outputs:
        inner = child.op("out1")
        print("   %-5s osc %4d chans -> %s %4d chans"
              % (stream, osc.numChans, child.name,
                 0 if inner is None else inner.numChans))
        if osc.numChans == 0:
            print("         (zero until something SENDS on port %d - the OSC In "
                  "CHOP creates" % osc.par.port.eval())
            print("          channels as they arrive, so an idle port looks "
                  "exactly like this)")
    print()
    print("   NEXT, in order: td_add_filter.py, td_add_derive.py,")
    print("   td_add_temporal.py, td_add_latches.py, td_add_coords.py,")
    print("   td_add_screenspace.py, td_add_groups.py")
    print()
    print("   ONE output: merge_streams -> trim_empty -> out1, %d channels."
          % out.numChans)
    print("   Delete Empty Channels = %s. The LIST is written by td_add_groups.py,"
          % bool(par_empty.eval()))
    print("   which is the only thing that knows which groups are frozen - so run")
    print("   it after this, or the trim keeps whatever list it had.")
    print()
    # The device list and the status light, once, at the end - so a fresh build opens
    # with a populated menu and an honest colour rather than an empty dropdown and a
    # blank field. `refresh_cameras` enumerates in a subprocess and opens no device,
    # so this takes the camera from nothing and raises no permission prompt.
    try:
        # `previous` carries what `Camera` held BEFORE it was destroyed and re-appended
        # as a menu, which is the only place the old text-field value still exists.
        devices = control.module.refresh_cameras(comp, want=previous.get("Camera"))
        print("   Camera menu: %d device(s) - %s"
              % (len(devices), ", ".join(devices) or "none found"))
        print("   Status: %s" % control.module.set_state(comp))
    except Exception as problem:                    # noqa: BLE001 - reported, not fatal
        # A build that could not enumerate is still a working build: the menu keeps
        # whatever it had and `Refresh Camera List` is one click away.
        print("   (could not enumerate devices: %r - press Refresh Camera List)"
              % (problem,))

    # PUT THEM BACK, last, after every operator this builder makes exists. See
    # `was_at` above: the ones this script recreates rather than reuses had no
    # position to preserve at the moment they were placed, so `Keeplayout` is applied
    # here instead, from the snapshot taken before the destroy.
    if keep_layout(comp):
        restored = 0
        for child in comp.children:
            previous = was_at.get(child.name)
            if previous is not None and (child.nodeX, child.nodeY) != previous:
                child.nodeX, child.nodeY = previous
                restored += 1
        if restored:
            print("   Keep Layout: %d operator(s) put back where you had them"
                  % restored)

    print("   Reference a fingertip as:  op('%s/hands')['h0_index_tip_tx']"
          % comp.path)
    print("   ...or off the single output:  op('%s')['h0_index_tip_tx']" % comp.path)
    print("=" * 70)


def _at(node, xy, keep, existed):
    """Write nodeX/nodeY unless `Keeplayout` is on and the node already existed.

    The rule lives in `appletd.td_layout.placement`, including what the flag
    cannot hold: anything a builder destroys and regenerates, which is every
    operator inside a group.
    """
    from appletd.td_layout import placement

    where = placement(xy, keep, existed)
    if where is not None:
        node.nodeX, node.nodeY = where
    return node


def _retire(comp, par_names, page_names):
    """Destroy named custom parameters, then any of `page_names` left empty.

    Returns what it removed, for the build report.

    Why parameters are destroyed rather than moved: TouchDesigner has no "move to
    another page", so a parameter that changes page is a destroy plus an append -
    and the append CANNOT run first, because the name would exist twice. Hence this
    is called before anything is appended, with `previous` already captured so a
    tuned value survives the round trip.

    Why the page is only destroyed when EMPTY: another builder may own something on
    it. `Advanced` is shared by this script and td_add_temporal.py, and destroying a
    page takes its parameters with it - which is exactly how a tuned threshold would
    disappear without anything saying so.
    """
    gone = []
    for name in par_names:
        par = getattr(comp.par, name, None)
        if par is not None:
            par.destroy()
            gone.append(name)
    for name in page_names:
        for page in list(comp.customPages):
            if page.name != name:
                continue
            leftover = [par.name for par in page.pars]
            if leftover:
                # Reported, not forced. A page this script thinks is finished but
                # which still holds something belongs to somebody else now.
                print("   (page %r still holds %s - left in place)"
                      % (name, ", ".join(leftover)))
            else:
                page.destroy()
                gone.append("page:" + name)
    return gone


def _page(comp, name):
    """Find or create a custom page. TRAP: `appendCustomPage` with an existing name
    creates a SECOND page of that name, and the duplicate holds different
    parameters (DESIGN.md 2.11)."""
    for existing in comp.customPages:
        if existing.name == name:
            return existing
    return comp.appendCustomPage(name)


STREAM_NOTES = """%(stream)s - one vision stream, from the port to the output.

  in1 -> filter -> coords ----+
                             |
         derive_chop --------+-> merge_out -> screen_only -> out1
         temporal -----------+
         latches ------------+

Row 0 is the DATA PATH; everything below it only reads the stream. That is why
`filter` cannot be gated by allowCooking - freezing it would freeze every position
rather than bypass the filter - while `coords`, `temporal` and `latches` can be.

EACH CONSUMER STATES ITS OWN INPUT, and that is load-bearing. An earlier version
had td_add_filter.py push a named list of consumers onto its output; two of the
names had moved inside the `coords` group and `derive_chop` does not exist yet when
the filter is built, so it wired itself to the RAW input and stayed there - every
derived attribute computed on unsmoothed landmarks while the coordinate spaces used
smoothed ones. Build order cannot be depended on; a consumer naming its own source
can.

merge_out IS THE ONLY JOIN, and a Merge CHOP accepts the same operator on any
number of inputs, silently. The only symptom is the channel count - `filter` once
reached three connections and put 274 duplicate channels on the output. Every
builder attaches through `_attach_once`, which dedupes by OWNER OBJECT, because
`.inputs` reports a group COMP as its inner `out1` and a name-keyed dedup collapsed
two groups into one and dropped 168 channels.

Built by tools/td_build_vision.py and six more builders. Edits here are overwritten.
"""


def _place_shell(td, child, stream, keep):
    """Re-apply the stream shell's positions, and its notes DAT. Every run.

    Separate from `_shell` because that one only runs for a NEW stream: an existing
    child already holds the networks six other builders own, so its INSIDES must not
    be rebuilt - but its layout should still follow the current table.

    `keep` is `Keeplayout`: with it on, an operator that already existed keeps
    whatever position it has. The notes DAT's TEXT is rewritten either way - the flag
    is about arrangement, not about letting documentation go stale.
    """
    from appletd.td_layout import placement, stream_xy

    for name in ("in1", "merge_out", "out1"):
        node = child.op(name)
        if node is None:
            continue
        where = placement(stream_xy(name), keep, True)
        if where is not None:
            node.nodeX, node.nodeY = where
    existing = child.op("notes")
    notes = existing or child.create(td.textDAT, "notes")
    where = placement(stream_xy("notes"), keep, existing is not None)
    if where is not None:
        notes.nodeX, notes.nodeY = where
    notes.text = STREAM_NOTES % {"stream": stream.upper()}


def _shell(td, child):
    """The empty stream network: in1 -> merge_out -> out1.

    One Merge with one input today, so every group builder attaches itself to it
    rather than restructuring anything - the discipline that survived contact is
    `_attach_once`, and it needs a Merge to attach to.

    `screen_only` is NOT built here: it belongs between `merge_out` and `out1` and
    `tools/td_add_screenspace.py` owns it, so it survives this builder running again
    on an existing stream - which is exactly when this function does not run at all.

    Positions come from `_place_shell`, which the caller runs afterwards on a new
    and an existing stream alike.
    """
    for existing in list(child.children):
        existing.destroy()
    chop_in = child.create(td.inCHOP, "in1")
    merge = child.create(td.mergeCHOP, "merge_out")
    merge.inputConnectors[0].connect(chop_in)
    chop_out = child.create(td.outCHOP, "out1")
    chop_out.inputConnectors[0].connect(merge)


main()
