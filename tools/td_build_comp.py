# The Parameter Execute DAT that turns a button press into a call.
SIDECAR_CALLBACK_SOURCE = '''# Generated by tools/td_build_comp.py
#
# TouchDesigner calls onPulse when a pulse parameter is pressed. The work lives
# in sidecar_control so it can also be called directly:
#     op('/project1/visionhands/sidecar_control').module.status()


def onPulse(par):
    control = op("sidecar_control").module
    if par.name == "Startsidecar":
        pid = control.start()
        par.owner.par.Sidecarpid = pid
    elif par.name == "Stopsidecar":
        stopped = control.stop()
        par.owner.par.Sidecarpid = 0
        print("[visionhands] stopped %d process(es)" % stopped)
    elif par.name == "Sidecarstatus":
        print("[visionhands] " + control.status())
'''

# Stops the sidecar when the project closes. Belt and braces with the sidecar's
# own parent-pid watch: this handles a clean quit, that handles a crash.
SIDECAR_EXIT_SOURCE = '''# Generated by tools/td_build_comp.py


def onExit():
    op("sidecar_control").module.stop()
'''

PARENT_PATH = "/project1"
COMP_NAME = "visionhands"
SOURCE_CHOP = "visionhands_osc"
OSC_PORT = 10000
REPO_ROOT = "/Users/omer/Documents/GitHub/visionhands-touchdesigner"
SIDECAR_PYTHON = "/Users/omer/.venvs/visionhands/bin/python"

# Defaults for the aspect and pixel conversions. MEASURED: the sidecar requests
# and receives 1280x720 (DESIGN.md 2.6), and Vision is fastest there.
#
# These are COMP parameters rather than baked-in numbers so a different camera
# does not need a rebuild. They are NOT read from the incoming channels because
# the wire contract deliberately does not carry width and height - adding them
# would be a contract change to solve something a parameter already solves.
DEFAULT_WIDTH = 1280
DEFAULT_HEIGHT = 720

# TouchDesigner's Camera COMP defaults to an Ortho Width of 1.0, so the visible
# world space is x in [-0.5, +0.5] and y in [-0.5/aspect, +0.5/aspect]. Matching
# that default means the common case needs no tuning at all.
DEFAULT_ORTHO_WIDTH = 1.0


# The rename approach that is no longer needed, recorded because the knowledge
# cost something to get: TouchDesigner's Rename CHOP DOES support wildcard
# back-references, so `*_lm08_*` -> `*_index_tip_*` renames h0 and h1 and _x,
# _y and _conf from one rule (verified live). What it does NOT do is apply 21
# such rules pairwise - a space-separated From/To list applies the first
# replacement to everything the whole From list matches, which turned all 126
# landmark channels into `h0_wrist_x`, `h0_wrist_x1`, `h0_wrist_x2`... The
# working alternative is the second input, a name reference built from a Table
# DAT through a DAT to CHOP (its DAT arrives by PARAMETER, not by a wire - a
# DAT to CHOP has no CHOP input connector), but that renames by position.


def main():
    import td

    print("=" * 70)
    print("visionhands: building the translation COMP")
    print("=" * 70)

    parent = op(PARENT_PATH)
    if parent is None:
        print("FAIL no operator at %s" % PARENT_PATH)
        return

    comp = parent.op(COMP_NAME)
    existed = comp is not None
    previous = {}
    if existed:
        # Remember what the user tuned, so a rebuild restores it rather than
        # resetting it.
        for name in ("Resw", "Resh", "Orthowidth", "Renderw", "Renderh",
                     "Slotassign", "Streamhands", "Streampose", "Streamface"):
            if hasattr(comp.par, name):
                previous[name] = getattr(comp.par, name).eval()
    if comp is None:
        comp = parent.create(td.baseCOMP, COMP_NAME)
        print("1. created %s" % comp.path)
    else:
        # Rebuild the insides from scratch rather than patching them, so running
        # this twice cannot leave a half-old network behind.
        for child in list(comp.children):
            child.destroy()
        print("1. reusing %s (contents cleared)" % comp.path)
    comp.nodeX, comp.nodeY = 250, 0

    # -- custom parameters -------------------------------------------------
    page = comp.appendCustomPage("Visionhands")
    par_w = page.appendInt("Resw", label="Source Width")[0]
    par_h = page.appendInt("Resh", label="Source Height")[0]
    # `.default` always, `.val` only when the parameter is being created.
    # TD's appendInt/appendFloat replace a parameter's attributes on rebuild, so
    # assigning .val unconditionally silently snapped a tuned Orthowidth back to
    # 1.0 and put a correctly-aligned overlay back off-target - the exact failure
    # this COMP exists to prevent, caused by re-running its own builder.
    par_w.default = DEFAULT_WIDTH
    par_h.default = DEFAULT_HEIGHT
    if not existed:
        par_w.val, par_h.val = DEFAULT_WIDTH, DEFAULT_HEIGHT
    # Match your Camera COMP's Ortho Width. TD's default is 1.0.
    par_ortho = page.appendFloat("Orthowidth", label="Camera Ortho Width")[0]
    par_ortho.default = DEFAULT_ORTHO_WIDTH
    if not existed:
        par_ortho.val = DEFAULT_ORTHO_WIDTH

    par_rw = page.appendInt("Renderw", label="Render Width")[0]
    par_rh = page.appendInt("Renderh", label="Render Height")[0]
    par_rw.default = DEFAULT_WIDTH
    par_rh.default = DEFAULT_HEIGHT

    lifecycle = comp.appendCustomPage("Sidecar")
    # Slot assignment: h0 = the right hand, h1 = the left, whichever order Vision
    # reports them in (visionhands/slots.py). On the Sidecar page rather than with
    # the attribute toggles, because it is a property of the PROCESS and only takes
    # effect when one is started - putting it beside Start is what makes that
    # obvious. NOTE the behavioural consequence: with this on, a single LEFT hand
    # puts nothing in h0, so every h0_* channel reads zero and h1_* carries the
    # hand. That is what "h0 is always the right hand" means.
    par_slots = lifecycle.appendToggle("Slotassign",
                                       label="Assign Slots (restart to apply)")[0]
    par_slots.default = True
    # Which Vision requests the sidecar runs. LAUNCH FLAGS, read once when the
    # process starts (DESIGN.md 6.4) - hence "restart to apply" in both labels,
    # for the same reason `Slotassign` says it: there is no control channel into
    # a running sidecar and there is not going to be one.
    #
    # What the toggles save is INFERENCE, not channels. A disabled stream keeps
    # every one of its channels in TouchDesigner, reading zero, because TD's OSC
    # In CHOP creates channels as they arrive and a channel that vanishes breaks
    # its consumers silently (DESIGN.md 6.2).
    par_hands = lifecycle.appendToggle(
        "Streamhands", label="Hands Stream (restart to apply)")[0]
    par_pose = lifecycle.appendToggle(
        "Streampose", label="Body Pose Stream (restart to apply)")[0]
    par_face = lifecycle.appendToggle(
        "Streamface", label="Face Stream (restart to apply)")[0]
    par_hands.default = True
    # OFF by default: an existing project reads no pose channels, and turning it
    # on by default would make every one of them pay for an inference nothing
    # looks at.
    par_pose.default = False
    # Off for the same reason, and with one extra: the face stream publishes head
    # pose and the bounding box but NOT the 76 landmark points, because their split
    # across the 12 regions is unmeasured (visionhands/face_types.py). Turning it on
    # by default would advertise a contract that is about to grow.
    par_face.default = False
    # TRAP, MEASURED on this rebuild: a NEWLY APPENDED toggle takes val = 0,
    # whatever `.default` says. `Streamhands` came back with default True and val
    # False, so `start()` refused to launch anything - loudly, which is the only
    # reason it was noticed rather than being a hands stream that quietly stopped.
    #
    # This is the sibling of the recorded appendInt/appendFloat trap (which is
    # about an EXISTING parameter being reset). The rule that covers both: set
    # `.val` exactly when the PARAMETER is new, which is not the same question as
    # whether the COMP is new - and it was the COMP the first version asked about.
    # `previous` is the record of which parameters existed before this run.
    for name, parameter in (("Slotassign", par_slots),
                            ("Streamhands", par_hands), ("Streampose", par_pose),
                            ("Streamface", par_face)):
        if name not in previous:
            parameter.val = parameter.default

    lifecycle.appendPulse("Startsidecar", label="Start Sidecar")
    lifecycle.appendPulse("Stopsidecar", label="Stop Sidecar")
    lifecycle.appendPulse("Sidecarstatus", label="Print Status")
    par_pid = lifecycle.appendInt("Sidecarpid", label="Sidecar PID")[0]
    par_pid.readOnly = True
    # Read the render's real resolution and the camera's real ortho width when
    # they are there to read, so the common case needs no tuning at all.
    render = parent.op("render1")
    if render is not None:
        par_rw.val = int(render.par.resolutionw.eval())
        par_rh.val = int(render.par.resolutionh.eval())
        print("   (took render %dx%d from %s)" % (par_rw.eval(), par_rh.eval(), render.path))
    elif not existed:
        par_rw.val, par_rh.val = DEFAULT_WIDTH, DEFAULT_HEIGHT

    camera = parent.op("cam1")
    if camera is not None and camera.par.projection.eval() == "ortho":
        par_ortho.val = float(camera.par.orthowidth.eval())
        print("   (took Orthowidth %.3f from %s)" % (par_ortho.eval(), camera.path))

    # Anything the user had tuned wins over the defaults above, except where we
    # just read a better answer from the actual camera and render.
    for name, value in previous.items():
        if name not in ("Orthowidth", "Renderw", "Renderh") or (
                render is None and camera is None):
            getattr(comp.par, name).val = value

    print("2. parameters: source %dx%d, render %dx%d, Orthowidth=%.3f, plus a Sidecar page"
          % (par_w.eval(), par_h.eval(), par_rw.eval(), par_rh.eval(), par_ortho.eval()))

    def make(kind, name, x, y):
        node = comp.create(kind, name)
        node.nodeX, node.nodeY = x, y
        return node

    # -- the network -------------------------------------------------------
    chop_in = make(td.inCHOP, "in1", -600, 0)

    print("3. no rename stage: the sidecar already sends readable joint names")
    print("   coordinate branches are built by tools/td_add_coords.py - see the")
    print("   build order in the comment above merge_out")

    # THE COORDINATE BRANCHES LIVE IN tools/td_add_coords.py NOW, as a `coords`
    # group COMP. Two reasons they moved out: twelve loose operators at this level
    # made the network unreadable, and this script destroys every child of the COMP
    # when it runs - so rebuilding the coordinate branches meant flattening
    # `filter`, `latches` and `temporal` too. One concern per builder is what makes
    # any one of them re-runnable (docs/BUILD_PLAN.md step 7.3).
    #
    # BUILD ORDER from scratch, and it matters because each group wires itself to
    # the one before:
    #     td_build_comp.py    this - the shell, the parameters, the sidecar control
    #     td_add_filter.py    `filter`, which everything downstream reads
    #     td_add_coords.py    `coords`
    #     td_add_derive.py    the stateless attributes
    #     td_add_temporal.py  `temporal` - presence, liveness, velocity
    #     td_add_latches.py   `latches`, which gates on temporal's `tmp_ready`
    #     td_add_groups.py    the Attributes page
    # Empty apart from the raw input. Each group builder attaches itself exactly
    # once, which is the only wiring discipline that has survived contact - see
    # `_attach_once` in tools/td_add_coords.py for the three ways piecemeal Merge
    # wiring failed first.
    merge = make(td.mergeCHOP, "merge_out", 450, 0)
    merge.inputConnectors[0].connect(chop_in)

    chop_out = make(td.outCHOP, "out1", 650, 0)
    chop_out.inputConnectors[0].connect(merge)

    # -- sidecar lifecycle -------------------------------------------------
    control = comp.create(td.textDAT, "sidecar_control")
    control.nodeX, control.nodeY = -600, 200
    control.text = SIDECAR_CONTROL_SOURCE % {
        "python": SIDECAR_PYTHON, "repo": REPO_ROOT, "port": OSC_PORT,
        "comp": comp.path}

    callbacks = comp.create(td.parameterexecuteDAT, "sidecar_callbacks")
    callbacks.nodeX, callbacks.nodeY = -350, 200
    callbacks.text = SIDECAR_CALLBACK_SOURCE
    callbacks.par.op = comp.path
    callbacks.par.pars = "Startsidecar Stopsidecar Sidecarstatus"
    callbacks.par.active = True
    callbacks.par.onpulse = True
    callbacks.par.custom = True

    on_exit = comp.create(td.executeDAT, "sidecar_exit")
    on_exit.nodeX, on_exit.nodeY = -100, 200
    on_exit.text = SIDECAR_EXIT_SOURCE
    on_exit.par.active = True
    on_exit.par.exit = True

    print("4. built %d operators, including sidecar Start/Stop" % len(comp.children))

    # -- wire the OSC CHOP in ---------------------------------------------
    source = parent.op(SOURCE_CHOP)
    if source is None:
        print("5. no %s to wire up - run tools/td_setup_osc.py first" % SOURCE_CHOP)
    else:
        comp.inputConnectors[0].connect(source)
        print("5. wired %s -> %s" % (source.path, comp.path))

    comp.cook(force=True)
    out_chop = comp.op("out1")
    print()
    print("6. output: %d channels" % out_chop.numChans)
    names = [c.name for c in out_chop.chans()]
    for probe in ("h0_wrist_x", "h0_index_tip_x", "h0_index_tip_tx",
                  "h0_index_tip_px", "h0_index_tip_conf", "n_hands", "age_ms"):
        mark = "ok " if probe in names else "MISSING"
        value = ""
        channel = out_chop.chan(probe)
        if channel is not None:
            value = " = %.4f" % channel[0]
        print("   %-8s %s%s" % (mark, probe, value))
    print()
    print("   Reference a fingertip as:  op('%s')['h0_index_tip_tx']" % comp.path)
    print()
    print("   Sidecar page on %s:" % comp.path)
    print("     Start Sidecar / Stop Sidecar / Print Status")
    print("     Streams (all restart-to-apply): hands %s | pose %s | face %s"
          % ("on" if comp.par.Streamhands.eval() else "off",
             "on" if comp.par.Streampose.eval() else "off",
             "on" if comp.par.Streamface.eval() else "off"))
    print("     Body pose arrives on port %d - run tools/td_build_pose_comp.py"
          % (OSC_PORT + 1))
    print("     Face arrives on port %d - run tools/td_build_face_comp.py"
          % (OSC_PORT + 2))
    print("   Stop finds ANY running sidecar, including one started from a")
    print("   terminal, and the project's exit stops it too.")
    print("=" * 70)


main()
