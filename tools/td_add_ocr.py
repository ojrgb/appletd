#!/usr/bin/env python
"""Text recognition: the read side, a Table DAT.

    RUN IT
        run("<repo>/tools/td_add_ocr.py")

    or through the chain: tools/td_rebuild.py, layer "ocr".

WHAT IT ADDS
    ocr_osc            an OSC In DAT on the text port (Oscport + 3), active with the toggle
    ocr_callbacks      its callback: one typed message a frame -> the table's rows
    ocr_table          a Table DAT: a header row, then one row per slot
    outtext            the COMP's sixth output, and its first DAT
    ocr_par_callbacks  blanks the table when `Streamocr` goes off
    Streamocr, Ocrlevel, Ocrlanguage, Ocrcorrect, Ocrlines, Ocrfound    on a Text page

WHY THE CALLBACK AND NOT THE DAT'S OWN TABLE. MEASURED: the OSC In DAT splits a string
argument on WHITESPACE into separate columns, so "Mind the gap" lands in three cells.
`onReceiveOSC` receives the typed arguments intact, spaces and UTF-8 included. One
message per frame is one callback per frame, and the rows are rewritten only when the
frame's `seq` moves and a cell actually changed - a static sign costs nothing downstream.

THE ROW COUNT FOLLOWS THE SIDECAR. `Ocrlines` is a launch flag; the table takes its
shape from the first frame that arrives after a restart, so the two cannot disagree.

Ref: appletd/text_types.py, appletd/ocr.py, DESIGN.md 6.4, docs/BUILD_PLAN.md step 28.
"""

import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MASTER_PATH = "/project1/appletd"

OSC = "ocr_osc"
CALLBACKS = "ocr_callbacks"
PAR_CALLBACKS = "ocr_par_callbacks"
TABLE = "ocr_table"
OUT = "outtext"
PAGE = "Text"

# What the OSC In DAT's callback runs on every message. `%(header)d` and
# `%(per_slot)d` are the wire layout from appletd/text_types.py, baked in as numbers
# so this DAT imports nothing on TouchDesigner's main thread.
CALLBACK_SOURCE = '''# Generated by tools/td_add_ocr.py
#
# One `/ocr` message per frame from the sidecar: seq, found, slots, then six
# arguments per slot (appletd/text_types.py). Written into the table only when `seq`
# moves and only into cells that changed, so a 60 Hz tick over a 30 Hz request costs
# one comparison, and a sign that is not moving costs nothing downstream either.
#
# `unpack_text_args` is a COPY of appletd.text_types.unpack_text_args, not an import:
# this runs on the main thread on every message. test_text_types.py holds the copy
# to the original.

ADDRESS = %(address)r
TABLE = %(table)r
COLUMNS = %(columns)r
TEXT_HEADER_ARGS = %(header)d
TEXT_ARGS_PER_SLOT = %(per_slot)d


# -- unpack: copied from appletd/text_types.py --
def unpack_text_args(args):
    if len(args) < TEXT_HEADER_ARGS:
        return None
    try:
        found, slots = int(float(args[1])), int(float(args[2]))
    except (TypeError, ValueError):
        return None
    if slots < 1 or len(args) != TEXT_HEADER_ARGS + TEXT_ARGS_PER_SLOT * slots:
        return None
    rows = []
    for index in range(slots):
        base = TEXT_HEADER_ARGS + TEXT_ARGS_PER_SLOT * index
        text = args[base]
        numbers = args[base + 1:base + TEXT_ARGS_PER_SLOT]
        try:
            cells = [format(float(value), ".4f") for value in numbers]
        except (TypeError, ValueError):
            return None
        rows.append([str(text), *cells])
    return found, slots, rows
# -- end unpack --


def write_rows(table, rows):
    """The header plus one row per slot. Reshaped only when the slot count moved."""
    if table.numRows != len(rows) + 1 or table.numCols != len(COLUMNS):
        table.clear()
        table.appendRow(list(COLUMNS))
        for row in rows:
            table.appendRow(row)
        return
    for index, row in enumerate(rows):
        for col, value in enumerate(row):
            cell = table[index + 1, col]
            if cell.val != value:
                cell.val = value


def onReceiveOSC(dat, rowIndex, message, bytes, timeStamp, address, args, peer):
    if address != ADDRESS or len(args) < TEXT_HEADER_ARGS:
        return
    comp = op.Appletd or dat.parent()
    table = comp.op(TABLE)
    if table is None:
        return
    try:
        seq = float(args[0])
    except (TypeError, ValueError):
        return
    if seq == dat.fetch("ocr_seq", None):
        return
    unpacked = unpack_text_args(args)
    if unpacked is None:
        return
    found, slots, rows = unpacked
    dat.store("ocr_seq", seq)
    write_rows(table, rows)
    found_par = getattr(comp.par, "Ocrfound", None)
    if found_par is not None and int(found_par.eval()) != found:
        found_par.val = found
'''

# `Streamocr` off: the OSC In DAT goes inactive through its own expression, so
# nothing more arrives - and the table would HOLD the last sign it saw, which is the
# frozen-value failure every other output here is built to avoid. So the rows are
# blanked, the way a disabled channel stream reads zeros.
PAR_CALLBACK_SOURCE = '''# Generated by tools/td_add_ocr.py
#
# A disabled text stream must read BLANK, not hold the last sign it saw. The OSC In
# DAT stops receiving through its `active` expression; this clears what it left.

TABLE = %(table)r
OSC = %(osc)r
BLANK_ROW = %(blank_row)r


def onValueChange(par, prev):
    comp = par.owner
    if par.name != "Streamocr" or bool(par.eval()):
        return
    table = comp.op(TABLE)
    if table is not None:
        for row in range(1, table.numRows):
            for col in range(table.numCols):
                table[row, col] = BLANK_ROW[col] if col < len(BLANK_ROW) else ""
    found = getattr(comp.par, "Ocrfound", None)
    if found is not None:
        found.val = 0
    osc = comp.op(OSC)
    if osc is not None:
        osc.unstore("ocr_seq")
'''


def main():
    import td

    if REPO_ROOT not in sys.path:
        sys.path.append(REPO_ROOT)
    for stale in [n for n in list(sys.modules)
                  if n == "appletd" or n.startswith("appletd.")]:
        del sys.modules[stale]
    from appletd.streams import (
        DEFAULT_OCR_LANGUAGE,
        DEFAULT_OCR_LEVEL,
        OCR_LEVELS,
        REQUEST_OCR,
        port_for,
    )
    from appletd.td_layout import OUTPUT_ORDER, ensure, keep_layout, master_xy
    from appletd.text_types import (
        DEFAULT_TEXT_LINES,
        MAX_TEXT_LINES,
        TEXT_ADDRESS,
        TEXT_ARGS_PER_SLOT,
        TEXT_COLUMNS,
        TEXT_HEADER_ARGS,
        blank_text_frame,
        pack_text_args,
        unpack_text_args,
    )

    comp = op(MASTER_PATH)
    if comp is None:
        print("no COMP at %s - run tools/td_build_vision.py first" % MASTER_PATH)
        return
    keep = keep_layout(comp)

    print("=" * 70)
    print("ocr: text recognition on %s" % comp.path)
    print("=" * 70)

    page = None
    for existing in comp.customPages:
        if existing.name == PAGE:
            page = existing
    if page is None:
        page = comp.appendCustomPage(PAGE)

    have = {par.name for par in comp.customPars}
    if "Streamocr" not in have:
        toggle = page.appendToggle(
            "Streamocr", label="Text Recognition  (6-60 ms a frame)")[0]
        toggle.default = False
    if "Ocrlevel" not in have:
        menu = page.appendMenu("Ocrlevel", label="Level")[0]
        menu.menuNames = list(OCR_LEVELS)
        menu.menuLabels = ["%s  (%s)" % (name.capitalize(), note)
                           for name, note in zip(OCR_LEVELS, ("5.9 ms", "48 ms"),
                                                 strict=True)]
        menu.default = DEFAULT_OCR_LEVEL
    if "Ocrlanguage" not in have:
        language = page.appendStr("Ocrlanguage",
                                  label="Language  (BCP 47; empty = detect)")[0]
        language.default = DEFAULT_OCR_LANGUAGE
        language.val = DEFAULT_OCR_LANGUAGE
    if "Ocrcorrect" not in have:
        correct = page.appendToggle("Ocrcorrect",
                                    label="Language Correction  (+2.4 ms)")[0]
        correct.default = False
    if "Ocrlines" not in have:
        lines = page.appendInt("Ocrlines", label="Table Rows  (restart)")[0]
        lines.min, lines.max = 1, MAX_TEXT_LINES
        lines.normMin, lines.normMax = 1, MAX_TEXT_LINES
        lines.clampMin = lines.clampMax = True
        lines.default = DEFAULT_TEXT_LINES
        lines.val = DEFAULT_TEXT_LINES
    if "Ocrfound" not in have:
        found = page.appendInt("Ocrfound", label="Lines Found  (this frame)")[0]
        found.default = 0
        found.readOnly = True

    # The rows a blank frame unpacks to, so what this builder and the toggle write
    # is byte-for-byte what a disabled sidecar sends.
    unpacked = unpack_text_args(pack_text_args(blank_text_frame(slots=1), 0.0))
    blank_row = unpacked[2][0]

    callbacks = ensure(comp, td.textDAT, CALLBACKS, master_xy(CALLBACKS), keep)
    callbacks.text = CALLBACK_SOURCE % {
        "address": TEXT_ADDRESS, "table": TABLE, "columns": tuple(TEXT_COLUMNS),
        "header": TEXT_HEADER_ARGS, "per_slot": TEXT_ARGS_PER_SLOT}

    table = ensure(comp, td.tableDAT, TABLE, master_xy(TABLE), keep)
    slots = int(comp.par.Ocrlines.eval())
    if table.numCols != len(TEXT_COLUMNS) or table.numRows < 2:
        table.clear()
        table.appendRow(list(TEXT_COLUMNS))
        for _ in range(slots):
            table.appendRow(list(blank_row))
    table.color = (0.35, 0.45, 0.5)

    existed = comp.op(OSC) is not None
    osc = ensure(comp, td.oscinDAT, OSC, master_xy(OSC), keep)
    if not existed:
        # Creating an OSC In DAT auto-creates a docked callbacks DAT. Ours is the
        # one above, so the stray goes - the same dance every Script TOP here does.
        for child in list(comp.children):
            if child.name.startswith(OSC + "_callbacks") and child.valid:
                child.destroy()
    # The port follows `Oscport` by expression, with the offset from the package,
    # so the receiver cannot end up listening where the sender is not sending.
    osc.par.port.expr = "op.Appletd.par.Oscport + %d" % port_for(REQUEST_OCR, 0)
    # Off with the toggle: nothing received, nothing cooked, for a project that
    # does not read text.
    osc.par.active.expr = "op.Appletd.par.Streamocr"
    osc.par.callbacks = callbacks.path
    # The DAT's own table is not read - the callback is the consumer - so it is kept
    # to one line rather than a growing log.
    osc.par.splitbundle = True
    osc.par.splitmessage = True
    osc.par.maxlines = 1
    osc.par.clamp = True
    osc.color = (0.35, 0.45, 0.5)

    par_exec = ensure(comp, td.parameterexecuteDAT, PAR_CALLBACKS,
                      master_xy(PAR_CALLBACKS), keep)
    par_exec.text = PAR_CALLBACK_SOURCE % {"table": TABLE, "osc": OSC,
                                           "blank_row": list(blank_row)}
    par_exec.par.op = comp.path
    par_exec.par.pars = "Streamocr"
    par_exec.par.valuechange = True

    out = ensure(comp, td.outDAT, OUT, master_xy(OUT), keep)
    out.inputConnectors[0].connect(table)
    # Pinned like every output: alphabetically `outtext` would land between `outmask`
    # and `outvideo` and renumber a live connector.
    out.par.connectorder = OUTPUT_ORDER[OUT]

    print("   %-18s port %s (%s), active with Streamocr, callbacks %s"
          % (OSC, osc.par.port.eval(), osc.par.port.expr, callbacks.name))
    print("   %-18s %d rows x %d columns: %s"
          % (TABLE, table.numRows, table.numCols, " ".join(TEXT_COLUMNS)))
    print("   %-18s connector %d" % (OUT, int(out.par.connectorder.eval())))
    print("   Streamocr = %s, level %s, language %r, correction %s, %d rows"
          % (bool(comp.par.Streamocr.eval()), comp.par.Ocrlevel.eval(),
             comp.par.Ocrlanguage.eval(), bool(comp.par.Ocrcorrect.eval()), slots))
    print()
    print("   Boxes are normalised, origin bottom-left: x1,y1 is the bottom-left corner")
    print("   and x2,y2 the top-right, like h0_bbox_*. Rows read top of image first.")


main()
