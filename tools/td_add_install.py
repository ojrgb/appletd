def main():
    import td

    if REPO_ROOT not in sys.path:
        sys.path.append(REPO_ROOT)
    # TouchDesigner caches our modules for the life of the process. DESIGN.md 2.11.
    for stale in [n for n in list(sys.modules)
                  if n == "appletd" or n.startswith("appletd.")]:
        del sys.modules[stale]
    from appletd.td_layout import master_xy, placement

    comp = op(MASTER_PATH)
    if comp is None:
        print("FAIL no COMP at %s - run tools/td_build_vision.py first" % MASTER_PATH)
        return

    print("=" * 70)
    print("install: the button, the status and the module that does the work")
    print("=" * 70)

    keep = bool(comp.par.Keeplayout.eval())
    existing = {par.name: par for par in comp.customPars}

    vision = advanced = None
    for page in comp.customPages:
        if page.name == "Vision":
            vision = page
        elif page.name == "Advanced":
            advanced = page
    if vision is None or advanced is None:
        print("FAIL no Vision/Advanced page - run tools/td_build_vision.py first")
        return

    # Append only what is absent. `appendPulse` on an existing parameter resets it,
    # and a reset fires a deferred callback that outlives a restore - which is how
    # `Verbosity` ended up on "Minimal" with every derive group off (DESIGN.md 2.11).
    if "Install" not in existing:
        vision.appendPulse("Install", label="Install")
    if "Installstate" not in existing:
        par = vision.appendStr("Installstate", label="Install Status")[0]
        par.readOnly = True
    else:
        existing["Installstate"].readOnly = True
    if "Forceinstall" not in existing:
        advanced.appendPulse(
            "Forceinstall", label="Force Install  (ignores the probe)")
    print("1. Install and Installstate on Vision, Forceinstall on Advanced")

    # The Vision page order: the install comes FIRST, because nothing else on the page
    # can work until it is done.
    order = ["Install", "Installstate"] + [
        p.name for p in vision.pars if p.name not in ("Install", "Installstate")]
    vision.sort(*order)

    for name, source, subs in (
            (CONTROL, CONTROL_SOURCE, {"comp": MASTER_PATH, "log": LOG_PATH,
                                       "control": CONTROL}),
            (CALLBACKS, CALLBACK_SOURCE, {"control": CONTROL}),
            (ON_START, START_SOURCE,
             {"control_path": MASTER_PATH + "/" + CONTROL})):
        dat = comp.op(name)
        existed = dat is not None
        if dat is None:
            kind = (td.parameterexecuteDAT if name == CALLBACKS
                    else td.executeDAT if name == ON_START else td.textDAT)
            dat = comp.create(kind, name)
        dat.text = source % subs
        where = placement(master_xy(name), keep, existed)
        if where is not None:
            dat.nodeX, dat.nodeY = where
        if name == CALLBACKS:
            dat.par.ops = comp.path
            dat.par.pars = "Install Forceinstall"
            dat.par.custom = True
            dat.par.builtin = False
            dat.par.onpulse = True
            dat.par.valuechange = False
            dat.par.active = True
        elif name == ON_START:
            dat.par.active = True
            dat.par.start = True
        print("   %-18s %s" % (name, "reused" if existed else "created"))

    # -- verification ------------------------------------------------------
    failures = []
    if comp.op("src") is None:
        failures.append("no `src` container - run tools/td_embed_package.py, or the "
                        "panel has nothing to read its own logic out of")
    elif comp.op("src/install") is None:
        failures.append("`src` has no `install` DAT - re-run "
                        "tools/td_embed_package.py")
    for name in ("Install", "Installstate", "Forceinstall", "Installroot",
                 "Sidecarpython", "Sourceversion"):
        if not hasattr(comp.par, name):
            failures.append("parameter %s is missing" % name)

    control = comp.op(CONTROL)
    reported = None
    if control is not None and not failures:
        try:
            reported = control.module.state()
        except Exception as problem:            # noqa: BLE001 - reported, not hidden
            failures.append("state() raised: %r" % problem)

    print()
    if failures:
        print("FAILURES (%d):" % len(failures))
        for failure in failures:
            print("   " + failure)
    else:
        print("   verified. Installstate reads: %s" % reported)
        print("   Install is %s"
              % ("greyed out - nothing to do"
                 if not comp.par.Install.enable else "live"))
    print()


main()
